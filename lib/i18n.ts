export const STRINGS: Record<Lang, Strings> = { te, hi, en };

/** An error that carries a problem code, so the screen can show it in the chosen language. */
export class Problem extends Error {
  code: ProblemCode;
  constructor(code: ProblemCode, detail?: string) { super(detail ?? code); this.name = "Problem"; this.code = code; }
}

/**
 * Word a problem for the chosen language. Problems with a code are fully translated.
 * Older two-part messages ("తెలుగు / English") keep the matching half; Hindi falls
 * back to a plain "not understood" line rather than showing Telugu.
 */
export function describe(cause: unknown, lang: Lang): string {
  const t = STRINGS[lang];
  if (cause instanceof Problem) return t.problems[cause.code];
  const message = cause instanceof Error ? cause.message : typeof cause === "string" ? cause : "";
  if (!message) return t.problems.RETRY;
  const [telugu, english] = message.split(" / ");
  if (lang === "te") return message;
  if (lang === "en") return english ?? (/[ఀ-౿]/.test(message) ? t.problems.UNCLEAR : message);
  return /[ఀ-౿]/.test(telugu) ? t.problems.UNCLEAR : english ?? message;
}
